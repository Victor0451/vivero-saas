import { createServerClient } from '@supabase/ssr'
import { NextResponse, type NextRequest } from 'next/server'

export async function middleware(request: NextRequest) {
  const { pathname } = request.nextUrl

  let response = NextResponse.next({
    request: {
      headers: request.headers,
    },
  })

  const supabase = createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        getAll() {
          return request.cookies.getAll()
        },
        setAll(cookiesToSet) {
          cookiesToSet.forEach(({ name, value }) => request.cookies.set(name, value))
          response = NextResponse.next({
            request: {
              headers: request.headers,
            },
          })
          cookiesToSet.forEach(({ name, value, options }) =>
            response.cookies.set(name, value, options)
          )
        },
      },
    }
  )

  const {
    data: { user },
  } = await supabase.auth.getUser()

  // Definir rutas que requieren autenticación
  const isProtectedRoute =
    pathname.startsWith('/dashboard') ||
    pathname.startsWith('/plantas') ||
    pathname.startsWith('/tareas') ||
    pathname.startsWith('/historial-clinico') ||
    pathname.startsWith('/onboarding') ||
    pathname.startsWith('/catalogos') ||
    pathname.startsWith('/configuracion')

  // Redirigir a login si no hay usuario y la ruta es protegida
  if (isProtectedRoute && !user) {
    const url = request.nextUrl.clone()
    url.pathname = '/login'
    url.searchParams.set('redirectTo', pathname)
    return NextResponse.redirect(url)
  }

  // Evitar que usuarios logueados entren a páginas de auth (login/register)
  const isAuthPage = pathname.startsWith('/login') || pathname.startsWith('/register')
  if (isAuthPage && user) {
    const url = request.nextUrl.clone()
    url.pathname = '/dashboard'
    return NextResponse.redirect(url)
  }

  return response
}

export const config = {
  matcher: [
    /*
     * Match all request paths except for the ones starting with:
     * - api (API routes)
     * - _next/static (static files)
     * - _next/image (image optimization files)
     * - favicon.ico (favicon file)
     * - public (images in public folder)
     */
    '/((?!api|_next/static|_next/image|favicon.ico|images|manifest.json).*)',
  ],
}